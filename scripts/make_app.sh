#!/bin/bash
# Builds Engram.app: a Spotlight-launchable app that starts the Second Mind
# server (if it is not already running) and opens it in its own window.
# Usage: scripts/make_app.sh [dest-dir]   (default /Applications)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-/Applications}/Engram.app"
PY="$(command -v python3)"

rm -rf "$DEST"
mkdir -p "$DEST/Contents/MacOS" "$DEST/Contents/Resources"
cp "$ROOT/scripts/Engram.icns" "$DEST/Contents/Resources/Engram.icns"

cat > "$DEST/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Engram</string>
  <key>CFBundleDisplayName</key><string>Engram</string>
  <key>CFBundleIdentifier</key><string>local.secondmind.engram</string>
  <key>CFBundleExecutable</key><string>Engram</string>
  <key>CFBundleIconFile</key><string>Engram</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSUIElement</key><true/>
</dict></plist>
PLIST

cat > "$DEST/Contents/MacOS/Engram" <<LAUNCH
#!/bin/bash
# Engram launcher (generated by scripts/make_app.sh).
PORT="\${SM_PORT:-7337}"
URL="http://127.0.0.1:\$PORT/"
LOG="\$HOME/Library/Logs/Engram.log"
up() { curl -s -o /dev/null --max-time 1 "\$URL"; }
if ! up; then
  cd "$ROOT" || exit 1
  SM_PORT="\$PORT" nohup "$PY" server.py >>"\$LOG" 2>&1 &
  for _ in \$(seq 50); do up && break; sleep 0.1; done
  up || { osascript -e 'display alert "Engram could not start" message "See ~/Library/Logs/Engram.log"'; exit 1; }
fi
if [ -d "/Applications/Google Chrome.app" ]; then
  open -na "Google Chrome" --args --app="\$URL"
else
  open "\$URL"
fi
LAUNCH
chmod +x "$DEST/Contents/MacOS/Engram"
touch "$DEST"
echo "Built $DEST"
